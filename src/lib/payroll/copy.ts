export type PayCopy = typeof EN;

export function payCopy(locale: string | null | undefined): PayCopy {
  return payLocale(locale) === "fr" ? FR : EN;
}

export function nextLabel(id: string, copy: PayCopy, dueLabel: string): string {
  if (id === "fix_shift") return copy.fixShift;
  if (id === "approve_hours") return copy.approveHours;
  if (id === "run_pay") return copy.startPay;
  if (id === "set_aside") return copy.setAside;
  if (id === "send_government") return dueLabel ? `${copy.sendMoney} · ${dueLabel}` : copy.sendMoney;
  return copy.allDone;
}

export function statusLabel(status: string, copy: PayCopy): string {
  if (status === "due_soon") return copy.statusSoon;
  if (status === "overdue") return copy.statusLate;
  if (status === "mismatch") return copy.statusMismatch;
  return copy.statusOn;
}

export function varianceWords(input: { locale: PayLocale; varianceCents: number; shortCents: number; money: (cents: number) => string; status: string }): string {
  if (input.varianceCents === 0 && input.shortCents === 0 && input.status !== "mismatch") {
    return input.locale === "fr" ? "Tout est correct" : "All good";
  }
  if (input.shortCents > 0) {
    const amount = input.money(input.shortCents);
    return input.locale === "fr" ? `Il manque ${amount}. Mettez ${amount} de plus de côté.` : `Short by ${amount}. Set aside ${amount} more.`;
  }
  if (input.status === "overdue") {
    return input.locale === "fr" ? "C'est en retard. Envoyez l'argent du gouvernement." : "This is late. Send the government money.";
  }
  if (input.status === "mismatch") {
    return input.locale === "fr" ? "Les montants ne correspondent pas. Vérifiez chaque ligne." : "The amounts do not match. Check each line.";
  }
  return input.locale === "fr" ? "Mis de côté, pas encore envoyé." : "Set aside, not sent yet.";
}
