export type DocPack = {
  title: Record<ProvinceCode, string>;
  prompts: Record<ProvinceCode, readonly string[]>;
  requirement: Record<ProvinceCode, string>;
};

function doc(
  title: Record<ProvinceCode, string>,
  prompts: Record<ProvinceCode, readonly string[]>,
  requirement: Record<ProvinceCode, string>,
): DocPack {
  return { title, prompts, requirement };
}

