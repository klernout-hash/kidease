const helperRoots = new Set(STARTUP_HELPER_ROOTS);

export function startupChunkGroup() {
  return {
    name: "startup-shared",
    tags: ["$initial"],
    priority: -10,
    minSize: 0,
    minShareCount: 1,
    // Rolldown recommends recursive dependencies to avoid invalid chunk cycles.
    includeDependenciesRecursively: true,
    test(id) {
      const normalized = id.replaceAll("\\", "/");
      const marker = normalized.lastIndexOf("/src/lib/");
      return helperRoots.has(marker >= 0 ? normalized.slice(marker + 1) : normalized);
    },
  };
}

/** Vite 8 environment gate: never change the Nitro/SSR chunk arrangement. */
export function startupChunksPlugin() {
  return {
    name: "kidease:startup-chunks",
    apply: "build",
    applyToEnvironment: (environment) => environment.name === "client",
    outputOptions(options) {
      if (this.environment?.name !== "client") return;
      return {
        ...options,
        codeSplitting: {
          ...options.codeSplitting,
          groups: [...(options.codeSplitting?.groups ?? []), startupChunkGroup()],
        },
      };
    },
  };
}
